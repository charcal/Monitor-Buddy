#!/usr/bin/env python3
"""Generates src/phone_buddy/font.h: two DejaVu Sans Bold bitmap fonts (ASCII
32-126) for the few screens Phone Buddy draws itself (setup, offline, no
Wi-Fi). The bridge draws everything else.

    python tools/eink_font.py [path/to/DejaVuSans-Bold.ttf] > src/phone_buddy/font.h
"""
import sys

from PIL import Image, ImageDraw, ImageFont

FIRST, LAST = 32, 126
SIZES = {"Small": 13, "Large": 20}


def glyphs(font):
    ascent, descent = font.getmetrics()
    height = ascent + descent
    out = []
    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        w = max(1, round(font.getlength(ch)))
        img = Image.new("1", (w, height), 0)
        ImageDraw.Draw(img).text((0, 0), ch, font=font, fill=1)
        stride = (w + 7) // 8
        rows = []
        for y in range(height):
            for bx in range(stride):
                byte = 0
                for bit in range(8):
                    x = bx * 8 + bit
                    if x < w and img.getpixel((x, y)):
                        byte |= 0x80 >> bit
                rows.append(byte)
        out.append((ch, w, rows))
    return height, out


def emit(name, size, path):
    font = ImageFont.truetype(path, size)
    height, gl = glyphs(font)
    lines = [f"// {name}: DejaVu Sans Bold {size}px, {height} rows a glyph"]
    lines.append(f"static const uint8_t k{name}Bits[] = {{")
    offsets, pos = [], 0
    for ch, w, rows in gl:
        offsets.append((w, pos))
        pos += len(rows)
        label = ch if ch not in "\\" else "backslash"
        lines.append("  " + ", ".join(f"0x{b:02X}" for b in rows) + f",  // '{label}'")
    lines.append("};")
    lines.append(f"static const Glyph k{name}Glyphs[] = {{")
    lines.append("  " + ", ".join(f"{{{w}, {off}}}" for w, off in offsets))
    lines.append("};")
    lines.append(f"static const Font k{name} = {{{height}, k{name}Glyphs, k{name}Bits}};")
    return "\n".join(lines)


def main(argv):
    path = argv[1] if len(argv) > 1 else "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"
    print("// Generated by tools/eink_font.py. Do not edit; run the tool again.")
    print("// DejaVu fonts: Bitstream Vera licence (free to embed).")
    print("#pragma once\n#include <stdint.h>\n")
    print("struct Glyph { uint8_t width; uint16_t offset; };")
    print("struct Font { uint8_t height; const Glyph *glyphs; const uint8_t *bits; };")
    print(f"static const char kFontFirst = {FIRST}, kFontLast = {LAST};\n")
    for name, size in SIZES.items():
        print(emit(name, size, path))
        print()


if __name__ == "__main__":
    main(sys.argv)
