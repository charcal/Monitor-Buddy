#!/usr/bin/env python3
"""Generates src/phone_buddy/font.h: Monitor Buddy's 5x7 pixel font
(bridge/pixelfont.py) at sizes 2 and 3, for the few screens Phone Buddy draws
itself (setup, offline, off). The bridge draws everything else, in the same font.

    python tools/eink_font.py > src/phone_buddy/font.h
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "bridge"))
from pixelfont import GLYPHS  # noqa: E402

FIRST, LAST = 32, 126
SIZES = {"Small": 2, "Large": 3}


def glyph_rows(ch):
    """Lower case draws as upper case; anything else missing as '?'."""
    return GLYPHS.get(ch) or GLYPHS.get(ch.upper()) or GLYPHS["?"]


def emit(name, size):
    w, h = 6 * size, 7 * size   # one font pixel = size x size; 1-pixel gap after each glyph
    stride = (w + 7) // 8
    lines = [f"// {name}: the 5x7 font at size {size}, {w} x {h} a glyph"]
    lines.append(f"static const uint8_t k{name}Bits[] = {{")
    offsets, pos = [], 0
    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        rows = glyph_rows(ch)
        data = []
        for y in range(h):
            row = rows[y // size]
            for bx in range(stride):
                byte = 0
                for bit in range(8):
                    x = bx * 8 + bit
                    if x < 5 * size and row[x // size] == "#":
                        byte |= 0x80 >> bit
                data.append(byte)
        offsets.append(pos)
        pos += len(data)
        label = {"\\": "backslash", "'": "quote"}.get(ch, ch)
        lines.append("  " + ", ".join(f"0x{b:02X}" for b in data) + f",  // {label}")
    lines.append("};")
    lines.append(f"static const Glyph k{name}Glyphs[] = {{")
    lines.append("  " + ", ".join(f"{{{w}, {off}}}" for off in offsets))
    lines.append("};")
    lines.append(f"static const Font k{name} = {{{h}, k{name}Glyphs, k{name}Bits}};")
    return "\n".join(lines)


def main():
    print("// Generated by tools/eink_font.py from bridge/pixelfont.py. Do not edit; run the tool again.")
    print("#pragma once\n#include <stdint.h>\n")
    print("struct Glyph { uint8_t width; uint16_t offset; };")
    print("struct Font { uint8_t height; const Glyph *glyphs; const uint8_t *bits; };")
    print(f"static const char kFontFirst = {FIRST}, kFontLast = {LAST};\n")
    for name, size in SIZES.items():
        print(emit(name, size))
        print()


if __name__ == "__main__":
    main()
